const INDUSTRY_LIST = INDUSTRY_GROUPS.flatMap(g => g.items.map(it => ({ ...it, group: g.group })));
const INDUSTRY_BY_NAME = Object.fromEntries(INDUSTRY_LIST.map(it => [it.name, it]));

/** テキスト（募集要項・企業名など）から業界を推定。候補を点数順で返す */
function guessIndustries(text) {
  if (!text) return [];
  const scores = INDUSTRY_LIST.map(it => {
    let score = 0;
    for (const k of it.kw) {
      // 短い英字キーワード（SE, EC など）は単語として出てきたときだけ数える
      const re = /^[A-Za-z0-9]{1,4}$/.test(k)
        ? new RegExp(`(^|[^A-Za-z])${k}([^A-Za-z]|$)`, 'g')
        : new RegExp(k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
      const n = (text.match(re) || []).length;
      if (n) score += Math.min(n, 3) * (k.length >= 4 ? 2 : 1);
    }
    return { it, score };
  }).filter(x => x.score > 0);
  scores.sort((a, b) => b.score - a.score);
  // 1位と比べて点数が低すぎる候補（たまたま単語が出てきただけのもの）は除く
  const top = scores[0]?.score || 0;
  return scores.filter(x => x.score >= Math.max(2, top * 0.4)).map(x => x.it);
}
